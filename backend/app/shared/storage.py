"""Object storage behind one small interface.

Browsers upload straight to storage with a short-lived signed form (S3 presigned POST or the local backend's HMAC
equivalent), so file bytes never pass through the API process in production. Every key is generated by the server
under ``tenants/{tenant_id}/``; clients never choose keys.

Backends
- ``S3Storage``: AWS S3, Cloudflare R2, SeaweedFS, MinIO. Signed URLs are built against ``S3_PUBLIC_ENDPOINT_URL``
  when set, so a browser outside Docker can reach the storage container while the API uses the internal network.
- ``LocalStorage``: files on disk, uploads and downloads through ``/api/v1/storage/local/*`` with HMAC-signed,
  expiring policies. Development and tests only; production refuses to boot with it.
"""

from __future__ import annotations

import asyncio
import base64
import hashlib
import hmac
import json
import os
import time
from dataclasses import dataclass, field
from functools import lru_cache
from pathlib import Path
from typing import Any, Protocol
from urllib.parse import quote

from app.core.config import get_settings


@dataclass
class UploadTarget:
    url: str
    fields: dict[str, str]
    method: str = "POST"
    expires_in: int = 0


@dataclass
class ObjectInfo:
    size: int
    content_type: str | None = None
    extra: dict[str, Any] = field(default_factory=dict)


class StorageError(Exception):
    pass


class Storage(Protocol):
    name: str

    def create_upload(self, key: str, *, content_type: str, max_bytes: int) -> UploadTarget: ...
    def download_url(self, key: str, *, filename: str, content_type: str, inline: bool) -> str: ...
    async def head(self, key: str) -> ObjectInfo | None: ...
    async def read(self, key: str, *, max_bytes: int, start: int = 0) -> bytes: ...
    async def delete(self, key: str) -> None: ...


def tenant_prefix(tenant_id: object) -> str:
    return f"tenants/{tenant_id}/"


def safe_filename(name: str, max_len: int = 120) -> str:
    """ASCII-only, no path separators; keeps the extension."""
    base = os.path.basename(name.replace("\\", "/")).strip() or "file"
    cleaned = "".join(c if c.isalnum() or c in "._-" else "-" for c in base)
    cleaned = cleaned.lstrip(".") or "file"
    if len(cleaned) > max_len:
        stem, dot, ext = cleaned.rpartition(".")
        cleaned = (stem[: max_len - len(ext) - 1] + "." + ext) if dot and len(ext) <= 10 else cleaned[:max_len]
    return cleaned


def content_disposition(filename: str, inline: bool) -> str:
    kind = "inline" if inline else "attachment"
    ascii_name = filename.encode("ascii", "ignore").decode() or "file"
    ascii_name = ascii_name.replace('"', "")
    return f"{kind}; filename=\"{ascii_name}\"; filename*=UTF-8''{quote(filename)}"


# --- S3-compatible ------------------------------------------------------------------------------------------


class S3Storage:
    name = "s3"

    def __init__(self) -> None:
        import boto3
        from botocore.config import Config

        s = get_settings()
        self.bucket = s.storage_bucket
        cfg = Config(signature_version="s3v4", s3={"addressing_style": "path" if s.s3_force_path_style else "auto"},
                     retries={"max_attempts": 3, "mode": "standard"})
        common = {"region_name": s.s3_region, "aws_access_key_id": s.s3_access_key_id,
                  "aws_secret_access_key": s.s3_secret_access_key, "config": cfg}
        self._client = boto3.client("s3", endpoint_url=s.s3_endpoint_url, **common)
        public = s.s3_public_endpoint_url or s.s3_endpoint_url
        self._signer = self._client if public == s.s3_endpoint_url else boto3.client("s3", endpoint_url=public,
                                                                                    **common)
        self._upload_ttl = s.storage_upload_url_ttl_seconds
        self._download_ttl = s.storage_download_url_ttl_seconds

    def create_upload(self, key: str, *, content_type: str, max_bytes: int) -> UploadTarget:
        post = self._signer.generate_presigned_post(
            Bucket=self.bucket, Key=key,
            Fields={"Content-Type": content_type},
            Conditions=[{"Content-Type": content_type}, ["content-length-range", 1, max_bytes]],
            ExpiresIn=self._upload_ttl,
        )
        return UploadTarget(url=post["url"], fields=post["fields"], expires_in=self._upload_ttl)

    def download_url(self, key: str, *, filename: str, content_type: str, inline: bool) -> str:
        return self._signer.generate_presigned_url(
            "get_object",
            Params={"Bucket": self.bucket, "Key": key, "ResponseContentType": content_type,
                    "ResponseContentDisposition": content_disposition(filename, inline)},
            ExpiresIn=self._download_ttl,
        )

    async def head(self, key: str) -> ObjectInfo | None:
        from botocore.exceptions import ClientError

        try:
            r = await asyncio.to_thread(self._client.head_object, Bucket=self.bucket, Key=key)
        except ClientError as e:
            if e.response.get("Error", {}).get("Code") in ("404", "NoSuchKey", "NotFound"):
                return None
            raise StorageError(str(e)) from e
        return ObjectInfo(size=int(r["ContentLength"]), content_type=r.get("ContentType"))

    async def read(self, key: str, *, max_bytes: int, start: int = 0) -> bytes:
        r = await asyncio.to_thread(self._client.get_object, Bucket=self.bucket, Key=key,
                                    Range=f"bytes={start}-{start + max_bytes - 1}")
        return await asyncio.to_thread(r["Body"].read)

    async def delete(self, key: str) -> None:
        await asyncio.to_thread(self._client.delete_object, Bucket=self.bucket, Key=key)

    def ensure_bucket(self) -> None:
        from botocore.exceptions import ClientError

        try:
            self._client.head_bucket(Bucket=self.bucket)
        except ClientError:
            self._client.create_bucket(Bucket=self.bucket)


# --- local filesystem ---------------------------------------------------------------------------------------


def _signing_key() -> bytes:
    return hashlib.sha256(b"xploads-storage-v1:" + get_settings().jwt_secret.encode()).digest()


def sign_payload(payload: dict[str, Any]) -> str:
    """``base64url(json).base64url(hmac)`` — compact, tamper-evident, expiring (``exp`` in payload)."""
    body = base64.urlsafe_b64encode(json.dumps(payload, separators=(",", ":"), sort_keys=True).encode()).rstrip(b"=")
    sig = base64.urlsafe_b64encode(hmac.new(_signing_key(), body, hashlib.sha256).digest()).rstrip(b"=")
    return f"{body.decode()}.{sig.decode()}"


def verify_payload(token: str, *, purpose: str) -> dict[str, Any] | None:
    try:
        body, sig = token.split(".", 1)
        expected = base64.urlsafe_b64encode(hmac.new(_signing_key(), body.encode(), hashlib.sha256).digest())
        if not hmac.compare_digest(expected.rstrip(b"=").decode(), sig):
            return None
        payload = json.loads(base64.urlsafe_b64decode(body + "=" * (-len(body) % 4)))
    except (ValueError, json.JSONDecodeError):
        return None
    if payload.get("p") != purpose or int(payload.get("exp", 0)) < time.time():
        return None
    return payload


class LocalStorage:
    name = "local"

    def __init__(self, root: str | None = None) -> None:
        s = get_settings()
        self.root = Path(root or s.storage_local_path).resolve()
        self.base = s.api_public_url.rstrip("/") + "/api/v1/storage/local"
        self._upload_ttl = s.storage_upload_url_ttl_seconds
        self._download_ttl = s.storage_download_url_ttl_seconds

    def path_for(self, key: str) -> Path:
        p = (self.root / key).resolve()
        if not p.is_relative_to(self.root) or ".." in Path(key).parts:
            raise StorageError("invalid key")
        return p

    def create_upload(self, key: str, *, content_type: str, max_bytes: int) -> UploadTarget:
        exp = int(time.time()) + self._upload_ttl
        policy = sign_payload({"p": "upload", "k": key, "ct": content_type, "max": max_bytes, "exp": exp})
        return UploadTarget(url=f"{self.base}/upload", fields={"policy": policy, "Content-Type": content_type},
                            expires_in=self._upload_ttl)

    def download_url(self, key: str, *, filename: str, content_type: str, inline: bool) -> str:
        exp = int(time.time()) + self._download_ttl
        token = sign_payload({"p": "download", "k": key, "ct": content_type, "fn": filename, "in": inline,
                              "exp": exp})
        return f"{self.base}/files/{token}"

    async def write(self, key: str, data: bytes, content_type: str) -> None:
        p = self.path_for(key)

        def _w() -> None:
            p.parent.mkdir(parents=True, exist_ok=True)
            tmp = p.with_suffix(p.suffix + ".part")
            tmp.write_bytes(data)
            tmp.replace(p)
            p.with_name(p.name + ".meta").write_text(json.dumps({"ct": content_type}))

        await asyncio.to_thread(_w)

    async def head(self, key: str) -> ObjectInfo | None:
        p = self.path_for(key)
        if not p.is_file():
            return None
        meta = p.with_name(p.name + ".meta")
        ct = json.loads(meta.read_text()).get("ct") if meta.is_file() else None
        return ObjectInfo(size=p.stat().st_size, content_type=ct)

    async def read(self, key: str, *, max_bytes: int, start: int = 0) -> bytes:
        p = self.path_for(key)

        def _r() -> bytes:
            with p.open("rb") as f:
                f.seek(start)
                return f.read(max_bytes)

        return await asyncio.to_thread(_r)

    async def delete(self, key: str) -> None:
        p = self.path_for(key)
        for f in (p, p.with_name(p.name + ".meta")):
            f.unlink(missing_ok=True)


@lru_cache
def get_storage() -> Storage:
    backend = get_settings().storage_backend
    return S3Storage() if backend == "s3" else LocalStorage()  # type: ignore[return-value]
